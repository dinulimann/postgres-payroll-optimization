#!/usr/bin/env bash
# Builds the schema, loads synthetic data and times each payroll version.
# Usage: ./scripts/bench.sh [n_employees]   (default 5000)
set -euo pipefail

cd "$(dirname "$0")/.."
N="${1:-5000}"
PERIOD="2026-09-01"
OUT="docs/results.md"

psql_db() { docker compose exec -T db psql -U payroll -d payroll -v ON_ERROR_STOP=1 -q -c "SET client_min_messages = warning" "$@"; }

# Runs one procedure and prints its wall-clock time in seconds.
timed_call() {
    local proc="$1" label="$2"
    psql_db -t -A -c "
        SET search_path TO payroll;
        CREATE TEMP TABLE t AS SELECT clock_timestamp() AS s;
        CALL ${proc}('${PERIOD}', '${label}');
        SELECT round(extract(epoch FROM clock_timestamp() - s)::numeric, 2) FROM t;" | tail -1
}

verify() {
    psql_db -t -A -F ' | ' -v ref=v1 -v cand="$1" -f /sql/07_verify.sql
}

echo "Starting PostgreSQL..."
docker compose up -d --wait >/dev/null

echo "Creating schema and $N synthetic employees..."
psql_db -f /sql/01_schema.sql
psql_db -v n_employees="$N" -f /sql/02_seed.sql >/dev/null
for f in 03_v1_naive 05_v2_cached 06_v3_set_based; do psql_db -f "/sql/$f.sql"; done

STATS=$(psql_db -t -A -F ' ' -c "SET search_path TO payroll;
    SELECT (SELECT count(*) FROM employees), (SELECT count(*) FROM assignments), (SELECT count(*) FROM attendance);")
read -r EMP ASG ATT <<<"$STATS"

echo "[1/4] v1 naive, no indexes..."
T1=$(timed_call v1_process_payroll v1)

echo "Adding indexes..."
psql_db -f /sql/04_indexes.sql

echo "[2/4] v1 naive + indexes..."
T2=$(timed_call v1_process_payroll v1_idx)
echo "[3/4] v2 cached..."
T3=$(timed_call v2_process_payroll v2)
echo "[4/4] v3 set-based..."
T4=$(timed_call v3_process_payroll v3)

V2=$(verify v1_idx); V3=$(verify v2); V4=$(verify v3)

speedup() { awk -v a="$T1" -v b="$1" 'BEGIN { printf "%.0fx", (b > 0 ? a / b : 0) }'; }

PG_VERSION=$(psql_db -t -A -c "SHOW server_version;")

cat >"$OUT" <<EOF
# Benchmark results

Generated by \`scripts/bench.sh $N\` on $(date '+%Y-%m-%d'), PostgreSQL $PG_VERSION in Docker,
$(uname -sm).

Data: $EMP employees, $ASG assignment rows, $ATT attendance rows (one month).

| Version | What changed | Time (s) | Speed-up vs v1 |
|---|---|---:|---:|
| v1 | Row-by-row loop, helper function per component, no indexes | $T1 | 1x |
| v1 + indexes | Same code, indexes from \`04_indexes.sql\` | $T2 | $(speedup "$T2") |
| v2 | Loop kept; params, rates, attendance and deductions pre-computed once | $T3 | $(speedup "$T3") |
| v3 | Fully set-based: two \`INSERT ... SELECT\` statements | $T4 | $(speedup "$T4") |

## Correctness check against v1

Rows that differ from v1 must be **0** for both tables.

| Run | Employees | Detail rows differing | Summary rows differing | Total net pay |
|---|---:|---:|---:|---:|
| $(echo "$V2" | sed 's/ | / | /g') |
| $(echo "$V3" | sed 's/ | / | /g') |
| $(echo "$V4" | sed 's/ | / | /g') |
EOF

cat "$OUT"
